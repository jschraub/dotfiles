def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    drift = []
    for relative, text in outputs().items():
        path = ROOT / relative
        if not path.exists() or path.read_text() != text:
            drift.append(relative)
            if not args.check:
                path.parent.mkdir(parents=True, exist_ok=True)
                # Config watchers must never observe an empty/truncated Lua/QML file.
                with tempfile.NamedTemporaryFile(mode='w', dir=path.parent, prefix='.atelier-', delete=False) as handle:
                    temporary = Path(handle.name)
                    handle.write(text)
                try:
                    temporary.chmod(0o644)
                    os.replace(temporary, path)
                finally:
                    temporary.unlink(missing_ok=True)
    if args.check and drift:
        parser.exit(1, 'Theme output drift:\n' + '\n'.join(drift) + '\n')
    print(f'Theme outputs {"checked" if args.check else "rendered"}: {len(outputs())}')


if __name__ == '__main__':
    main()
